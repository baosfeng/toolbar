import Foundation
import CryptoKit

// MARK: - 粘贴板类型常量

/// 剪贴板标记类型常量（与 NSPasteboard 类型名一致，Core 层不依赖 AppKit）
public enum ClipboardPasteboardType {
    /// 密码管理器等显式声明保密的内容
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// 瞬时内容（不应进入历史）
    public static let transient = "org.nspasteboard.TransientType"
    /// 程序自动生成而非用户复制
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// 本 App 自身写回剪贴板时的自激标记
    public static let internalMarker = "com.bsfeng.macmonitor.clipboard.internal"
}

// MARK: - 忽略判定

/// 忽略原因（命中即不采集、不落库，仅记 logger.debug）
public enum ClipboardIgnoreReason: String, Sendable, Equatable {
    /// 自激标记：本 App 自己写回的内容
    case internalMarker
    /// ConcealedType：显式保密
    case concealed
    /// TransientType：瞬时内容
    case transient
    /// AutoGeneratedType：程序生成
    case autoGenerated
    /// 用户黑名单 App
    case blacklistedApp

    /// 中文描述（日志与排查用）
    public var label: String {
        switch self {
        case .internalMarker: return "自激标记"
        case .concealed: return "保密类型"
        case .transient: return "瞬时类型"
        case .autoGenerated: return "自动生成类型"
        case .blacklistedApp: return "黑名单应用"
        }
    }
}

/// 忽略判定（纯函数，不触碰 NSPasteboard）
public enum ClipboardIgnorePolicy {

    /// 判定是否忽略本次剪贴板内容
    ///
    /// 判定优先级：自激标记 > 保密 > 瞬时 > 自动生成 > 黑名单应用（先命中先返回，便于日志定位）。
    /// - Parameters:
    ///   - typeNames: 当前剪贴板承载的全部类型名
    ///   - bundleID: 来源 App 的 bundleID（取不到时传 nil，此时不做黑名单判定）
    ///   - blacklistedBundleIDs: 用户黑名单
    /// - Returns: 忽略原因；nil 表示正常采集
    public static func ignoreReason(
        typeNames: [String],
        bundleID: String?,
        blacklistedBundleIDs: Set<String> = []
    ) -> ClipboardIgnoreReason? {
        if typeNames.contains(ClipboardPasteboardType.internalMarker) { return .internalMarker }
        if typeNames.contains(ClipboardPasteboardType.concealed) { return .concealed }
        if typeNames.contains(ClipboardPasteboardType.transient) { return .transient }
        if typeNames.contains(ClipboardPasteboardType.autoGenerated) { return .autoGenerated }
        if let bundleID, blacklistedBundleIDs.contains(bundleID) { return .blacklistedApp }
        return nil
    }

    /// 判断一个类型名是否属于系统/自激的忽略标记（供采集端快速短路）
    public static func isIgnoredTypeName(_ typeName: String) -> Bool {
        typeName == ClipboardPasteboardType.internalMarker
            || typeName == ClipboardPasteboardType.concealed
            || typeName == ClipboardPasteboardType.transient
            || typeName == ClipboardPasteboardType.autoGenerated
    }
}

// MARK: - 文本载荷

/// 待落库文本载荷（规范化 + 截断 + 去重哈希一次产出）
public struct ClipboardTextPayload: Equatable, Sendable {
    /// 规范化并按上限截断后的文本（落库用）
    public let text: String
    /// 完整规范化文本的 SHA256（去重口径，不受截断影响）
    public let contentHash: String
    /// 是否发生截断（超上限，仅记录前 maxBytes 字节）
    public let isTruncated: Bool
}

// MARK: - 内容哈希

/// 内容哈希与文本规范化（纯函数）
///
/// 哈希口径（与设计规格第 4 节一致）：
/// - 文本：换行统一为 \n + 去首尾空白后的 UTF-8 字节 SHA256，十六进制小写
/// - 图片：被选中表示的原始字节 SHA256（PNG 优先、TIFF 兜底，同一次复制只算一种表示）
public enum ClipboardContentHasher {

    /// 规范化文本：换行统一为 \n、去首尾空白
    /// - Returns: 规范化后的文本；空白串（含空串、纯空白）返回 nil，表示无需落库
    public static func normalizeText(_ text: String) -> String? {
        let unified = text
            .replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
        let trimmed = unified.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : trimmed
    }

    /// 准备待落库文本：规范化 + 计算哈希 + 超限截断
    ///
    /// 截断策略：超 maxBytes 时保留前 maxBytes 字节（按字符边界切，不切裂多字节字符），
    /// 哈希仍取完整规范化文本，保证超大内容之间不因截断而误判为重复。
    /// - Parameters:
    ///   - raw: 原始文本
    ///   - maxBytes: 落库字节上限（≤ 0 时取 ClipboardLimit.maxTextBytes）
    /// - Returns: 载荷；空内容返回 nil（调用方跳过本条）
    public static func prepareText(_ raw: String, maxBytes: Int = ClipboardLimit.maxTextBytes) -> ClipboardTextPayload? {
        guard let normalized = normalizeText(raw) else { return nil }
        let hash = sha256Hex(Data(normalized.utf8))
        let limit = maxBytes > 0 ? maxBytes : ClipboardLimit.maxTextBytes
        guard normalized.utf8.count > limit else {
            return ClipboardTextPayload(text: normalized, contentHash: hash, isTruncated: false)
        }
        return ClipboardTextPayload(text: truncate(normalized, toUTF8Bytes: limit),
                                    contentHash: hash,
                                    isTruncated: true)
    }

    /// 文本哈希（规范化后 UTF-8 字节 SHA256）
    /// - Returns: 十六进制小写哈希；空内容返回 nil
    public static func hash(text: String) -> String? {
        guard let normalized = normalizeText(text) else { return nil }
        return sha256Hex(Data(normalized.utf8))
    }

    /// 图片哈希（取被选中表示的原始字节）
    /// - Parameters:
    ///   - data: 原始字节（PNG 或 TIFF 其一）
    ///   - maxBytes: 大小上限（≤ 0 时取 ClipboardLimit.maxImageBytes）
    /// - Returns: 哈希；空数据或超过上限返回 nil（跳过落库，由调用方记 logger.debug）
    public static func prepareImageData(_ data: Data, maxBytes: Int = ClipboardLimit.maxImageBytes) -> String? {
        guard !data.isEmpty else { return nil }
        let limit = maxBytes > 0 ? maxBytes : ClipboardLimit.maxImageBytes
        guard data.count <= limit else { return nil }
        return sha256Hex(data)
    }

    /// 原始字节 SHA256（十六进制小写）
    public static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// 按 UTF-8 字节上限截断文本（按字符边界，不切裂多字节字符与组合字符）
    /// - Parameter maxBytes: 上限；≤ 0 返回空串
    public static func truncate(_ text: String, toUTF8Bytes maxBytes: Int) -> String {
        guard maxBytes > 0 else { return "" }
        guard text.utf8.count > maxBytes else { return text }
        var used = 0
        var result = ""
        result.reserveCapacity(maxBytes)
        for character in text {
            let size = String(character).utf8.count
            if used + size > maxBytes { break }
            result.append(character)
            used += size
        }
        return result
    }
}
